#!/usr/bin/env python3
"""
Adds the albums that are in the personal collection sheet but never made it
into the database -- records bought after the original Discogs import.

Confirmed missing by two passes: matched on Discogs release id, then again
on title alone (which caught "Celia Cruz, Willie Colón" and "Fela Kuti,
Africa 70" already being present under different pressings -- those are
deliberately NOT in the list below).

No Discogs token needed: this goes through the site's own /api/discogs
endpoint, which holds the token server-side. That also means it works from
anywhere, and there's no token to leak into this file.

    python3 build_missing_albums_sql.py

Writes import_missing.sql -- paste into the Supabase SQL Editor and run.
"""
